-- Phần A. Phân tích và viết các lệnh để xây dựng cơ sở dữ liệu dựa vào mô tả phía trên
CREATE DATABASE company_management CHAR SET utf8mb4;
USE company_management;

CREATE TABLE T01_EMPLOYEE(
	C01_EMPLOYEE_ID INT AUTO_INCREMENT,
    C01_EMPLOYEE_NAME VARCHAR(255) NOT NULL,
    C01_EMPLOYEE_DOB DATE NOT NULL,
    C01_GENDER BIT(1) NOT NULL,
    C01_ADDRESS VARCHAR(255) NOT NULL,
    C01_SALARY FLOAT NOT NULL,
    C01_START_DATE DATE NOT NULL,
    C01_DEPARTMENT_ID INT,
    PRIMARY KEY (C01_EMPLOYEE_ID)
);

CREATE TABLE T02_MANAGER(
	C02_MANAGER_ID INT AUTO_INCREMENT,
    C02_EMPLOYEE_ID INT,
    C02_MANAGER_START_DATE DATE NOT NULL,
    PRIMARY KEY (C02_MANAGER_ID),
	CONSTRAINT FK_T02_T01 FOREIGN KEY(C02_EMPLOYEE_ID) REFERENCES T01_EMPLOYEE(C01_EMPLOYEE_ID)
);

CREATE TABLE T03_DEPARTMENT(
	C03_DEPARTMENT_ID INT AUTO_INCREMENT,
    C03_DEPARTMENT_NAME VARCHAR(255) NOT NULL,
    C03_MANAGER_ID INT,
    PRIMARY KEY (C03_DEPARTMENT_ID),
    CONSTRAINT FK_T03_T02 FOREIGN KEY(C03_MANAGER_ID) REFERENCES T02_MANAGER(C02_MANAGER_ID)
);

