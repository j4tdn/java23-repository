-- Quẻies

SELECT t02.C02_NAME AS STUDENT_NAME,
	   t02.C02_GENDER AS GEMDER,
       t01.C01_TEACHER AS TEACHER_NAME
  FROM T02_STUDENT t02
  JOIN T01_CLASS t01 ON t02.C02_CLASS_ID = t01.C01_CLASS_ID;

SELECT t01.C01_TEACHER AS TEACHER_NAME,
 COUNT(t02.C02_STUDENT_ID) AS TOTAL_STUDENT
  FROM T01_CLASS t01
  JOIN T02_STUDENT t02 ON t01.C01_CLASS_ID = t02.C02_CLASS_ID
 WHERE t01.C01_CLASS_NAME = '12C'
 GROUP BY t01.C01_TEACHER;
 
SELECT t01.C01_CLASS_NAME AS CLASS_NAME,
	   t03.C03_SUBJECT AS SUBJECT,
 COUNT(DISTINCT T02.C02_STUDENT_ID) AS GOOD_STUDEMT_COUNT
  FROM T03_RESULT t03
  JOIN T02_STUDENT t02 ON t03.C03_STUDENT_ID = t02.C02_STUDENT_ID
  JOIN T01_CLASS t01 ON t02.C02_CLASS_ID = t01.C01_CLASS_ID
 WHERE t03.C03_SUBJECT IN ('Math', 'Literature') AND t03.C03_SCORE >= 8
 GROUP BY t01.C01_CLASS_NAME, t03.C03_SUBJECT;

SELECT *
  FROM T02_STUDENT
 ORDER BY C02_CLASS_ID;

