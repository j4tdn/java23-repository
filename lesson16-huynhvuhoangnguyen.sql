-- Phần C. Thực hiện truy vấn
-- 1. Liệt kê các dự án diễn ra trong năm *?* có số tiền thu được trên *?* triệu VND
SELECT C04_PR0JECT_NAME PR0JECT_NAME,
	   C04_INCOME INCOME
  FROM T04_PROJECT
 WHERE YEAR(C04_START_DATE) = 2022
   AND C04_INCOME > 10000000;

-- 2. Liệt kê các nhân viên đã tham gia hơn ?*? giờ trong các dự án, hiển thị chi tiết số giờ trong mỗi dự án mà nhân viên tham gia
SELECT t01.C01_EMPLOYEE_NAME AS EMPLOYEE_NAME,
       t04.C04_PR0JECT_NAME AS PR0JECT_NAME,
       t05.C05_WORK_HOURS AS WorkHours
  FROM T05_PROJECT_PATICIPATE t05
  JOIN T01_EMPLOYEE t01 ON t05.C05_EMPLOYEE_ID = t01.C01_EMPLOYEE_ID
  JOIN T04_PROJECT t04 ON t05.C05_PROJECT_ID = t04.C04_PROJECT_ID
 WHERE t05.C05_WORK_HOURS > 80;

-- 3. Liệt kê các nhân viên có mức lương >= mức lương của người giám sát/quản lý trực tiếp nhân viên đó
SELECT t01.C01_EMPLOYEE_ID EMPLOYEE_ID,
	   t01.C01_EMPLOYEE_NAME EMPLOYEE_NAME,
       t01.C01_SALARY EMPLOYEE_SALARY,
       t02.C02_MANAGER_ID MANAGER_ID,
       t11.C01_EMPLOYEE_NAME MANAGER_NAME,
       t11.C01_SALARY MANAGER_NAME_SALARY
FROM T01_EMPLOYEE t01
JOIN T02_MANAGER t02 ON t01.C01_DEPARTMENT_ID = t02.C02_MANAGER_ID
JOIN T01_EMPLOYEE t11 ON t02.C02_EMPLOYEE_ID = t11.C01_EMPLOYEE_ID
WHERE t01.C01_SALARY >= t11.C01_SALARY;

-- 4. Liệt kê các phòng ban có số lượng nhân viên lớn hơn *?*
SELECT t03.C03_DEPARTMENT_ID DEPARTMENT_ID,
	   t03.C03_DEPARTMENT_NAME DEPARTMENT_NAME,
       COUNT(t01.C01_EMPLOYEE_ID) EMPLOYEE_ID
  FROM T03_DEPARTMENT t03
  JOIN T01_EMPLOYEE t01 ON t03.C03_DEPARTMENT_ID = t01.C01_DEPARTMENT_ID
 GROUP BY t03.C03_DEPARTMENT_ID, t03.C03_DEPARTMENT_NAME
HAVING COUNT(t01.C01_EMPLOYEE_ID) > 2;

-- 5. Liệt kê các nhân viên đã làm việc cho công ty hơn ?*? năm
SELECT C01_EMPLOYEE_NAME EMPLOYEE_NAME,
       C01_START_DATE START_DATE
  FROM T01_EMPLOYEE
 WHERE C01_START_DATE < DATE_SUB(CURRENT_DATE, INTERVAL 5 YEAR);

-- 6. Liệt kê các nhân viên vừa là trưởng phòng ban, và là quản lý dự án
-- Truy vấn liệt kê các nhân viên vừa là trưởng phòng ban, vừa là quản lý dự án
SELECT t01.C01_EMPLOYEE_NAME C01_EMPLOYEE_NAME,
       t03.C03_DEPARTMENT_NAME DEPARTMENT_NAME,
       t04.C04_PR0JECT_NAME PR0JECT_NAME
  FROM T01_EMPLOYEE t01
  JOIN T02_MANAGER t02 ON t01.C01_EMPLOYEE_ID = t02.C02_EMPLOYEE_ID
  JOIN T03_DEPARTMENT t03 ON t03.C03_MANAGER_ID = t02.C02_MANAGER_ID
  JOIN T04_PROJECT t04 ON t04.C04_MANAGER_ID = t02.C02_MANAGER_ID
 GROUP BY t01.C01_EMPLOYEE_ID, t01.C01_EMPLOYEE_NAME, t03.C03_DEPARTMENT_NAME, t04.C04_PR0JECT_NAME;

-- 7. Liệt kê các nhân viên quản lý nhiều hơn 1 dự án
SELECT t01.C01_EMPLOYEE_NAME EMPLOYEE_NAME,
       COUNT(t04.C04_PROJECT_ID) NUMBER_OF_PROJECTS
FROM T02_MANAGER t02
JOIN T04_PROJECT t04 ON t02.C02_MANAGER_ID = t04.C04_MANAGER_ID
JOIN T01_EMPLOYEE t01 ON t02.C02_EMPLOYEE_ID = t01.C01_EMPLOYEE_ID
GROUP BY t02.C02_EMPLOYEE_ID, t01.C01_EMPLOYEE_NAME
HAVING COUNT(t04.C04_PROJECT_ID) > 1;

