SELECT 
    MADUAN, 
    TENDUAN, 
    NGAYBATDAU, 
    NGAYKETTHUC, 
    SOTIENTHUDUOC
FROM 
    T03_DUAN
WHERE 
    (YEAR(NGAYBATDAU) = 2022 OR YEAR(NGAYKETTHUC) = 2022) 
    AND SOTIENTHUDUOC > 800000000;

SELECT 
    NV.MANHANVIEN,
    NV.HOTEN,
    DA.MADUAN,
    DA.TENDUAN,
    TGDA.SOGIOLAMVIEC
FROM 
    T02_NHANVIEN NV
JOIN 
    T04_THAMGIADUAN TGDA ON NV.MANHANVIEN = TGDA.MANHANVIEN
JOIN 
    T03_DUAN DA ON TGDA.MADUAN = DA.MADUAN
WHERE 
    TGDA.SOGIOLAMVIEC > 250
ORDER BY 
    NV.MANHANVIEN, DA.MADUAN;

SELECT 
    NV.MANHANVIEN,
    NV.HOTEN,
    NV.LUONG AS LUONGNHANVIEN,
    QL.MANHANVIEN AS MANGUOIQUANLY,
    QL.HOTEN AS TENNGUOIQUANLY,
    QL.LUONG AS LUONGNGUOIQUANLY
FROM 
    T02_NHANVIEN NV
JOIN 
    T02_NHANVIEN QL ON NV.MANGUOIQUANLY = QL.MANHANVIEN
WHERE 
    NV.LUONG >= QL.LUONG;

SELECT 
    PB.MAPHONGBAN,
    PB.TENPHONGBAN,
    COUNT(NV.MANHANVIEN) AS SOLUONGNHANVIEN
FROM 
    T01_PHONGBAN PB
JOIN 
    T02_NHANVIEN NV ON PB.MAPHONGBAN = NV.MAPHONGBAN
GROUP BY 
    PB.MAPHONGBAN, PB.TENPHONGBAN
HAVING 
    COUNT(NV.MANHANVIEN) > 3;

SELECT 
    MANHANVIEN,
    HOTEN,
    NGAYVAOCONGTY,
    DATEDIFF(CURDATE(), NGAYVAOCONGTY)/365 AS SONAMLAMVIEC
FROM 
    T02_NHANVIEN
WHERE 
    DATEDIFF(CURDATE(), NGAYVAOCONGTY)/365 > 5;

SELECT DISTINCT
    NV.MANHANVIEN,
    NV.HOTEN,
    PB.MAPHONGBAN,
    PB.TENPHONGBAN AS PHONGBANQUANLY,
    GROUP_CONCAT(DA.MADUAN) AS DUANQUANLY
FROM 
    T02_NHANVIEN NV
JOIN 
    T01_PHONGBAN PB ON NV.MANHANVIEN = PB.MATRUONGPHONG
JOIN 
    T03_DUAN DA ON NV.MANHANVIEN = DA.MAQUANLYDUAN
GROUP BY 
    NV.MANHANVIEN, NV.HOTEN, PB.MAPHONGBAN, PB.TENPHONGBAN;

SELECT 
    NV.MANHANVIEN,
    NV.HOTEN,
    COUNT(DA.MADUAN) AS SOLUONGDUANQUANLY,
    GROUP_CONCAT(DA.MADUAN) AS DANHSACHDUANQUANLY
FROM 
    T02_NHANVIEN NV
JOIN 
    T03_DUAN DA ON NV.MANHANVIEN = DA.MAQUANLYDUAN
GROUP BY 
    NV.MANHANVIEN, NV.HOTEN
HAVING 
    COUNT(DA.MADUAN) > 1;
