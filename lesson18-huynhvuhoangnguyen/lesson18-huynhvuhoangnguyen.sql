CREATE DATABASE lesson18_exam CHAR SET utf8mb4;

USE lesson18_exam;

-- DDL

CREATE TABLE T01_CLASS (
    C01_CLASS_ID INT AUTO_INCREMENT,
    C01_CLASS_NAME VARCHAR(100) NOT NULL,
    C01_TEACHER VARCHAR(100) NOT NULL,
    PRIMARY KEY (C01_CLASS_ID)
);

CREATE TABLE T02_STUDENT (
    C02_STUDENT_ID INT AUTO_INCREMENT,
    C02_NAME VARCHAR(100) NOT NULL,
    C02_GENDER ENUM('Male', 'Female') NOT NULL,
    C02_CLASS_ID INT,
    PRIMARY KEY (C02_STUDENT_ID),
    CONSTRAINT FK_T02_T01 FOREIGN KEY (C02_CLASS_ID) REFERENCES T01_CLASS(C01_CLASS_ID)
);

CREATE TABLE T03_RESULT (
    C03_STUDENT_ID INT,
    C03_SUBJECT VARCHAR(100) NOT NULL,
    C03_SCORE DECIMAL(2,1) NOT NULL,
    PRIMARY KEY (C03_STUDENT_ID, C03_SUBJECT),
    CONSTRAINT FK_T03_T02 FOREIGN KEY (C03_STUDENT_ID) REFERENCES T02_STUDENT(C02_STUDENT_ID)
);

