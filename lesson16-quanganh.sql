CREATE DATABASE QUANLYCONGTY CHAR SET utf8mb4;
USE QUANLYCONGTY;

CREATE TABLE T01_PHONGBAN (
    MAPHONGBAN VARCHAR(10) PRIMARY KEY,
    TENPHONGBAN NVARCHAR(100) NOT NULL UNIQUE,
    MATRUONGPHONG VARCHAR(10),
    NGAYNHANCHUC DATE
);

CREATE TABLE T02_NHANVIEN (
    MANHANVIEN VARCHAR(10) PRIMARY KEY,
    HOTEN NVARCHAR(100) NOT NULL,
    DIACHI NVARCHAR(200),
    LUONG DECIMAL(15, 2) NOT NULL,
    GIOITINH NVARCHAR(10),
    NGAYSINH DATE,
    NGAYVAOCONGTY DATE NOT NULL,
    MAPHONGBAN VARCHAR(10),
    MANGUOIQUANLY VARCHAR(10)
);

CREATE TABLE T03_DUAN (
    MADUAN VARCHAR(10) PRIMARY KEY,
    TENDUAN NVARCHAR(100) NOT NULL UNIQUE,
    NGAYBATDAU DATE NOT NULL,
    NGAYKETTHUC DATE,
    SOTIENTHUDUOC DECIMAL(15, 2),
    MAQUANLYDUAN VARCHAR(10)
);

CREATE TABLE T04_THAMGIADUAN (
    MANHANVIEN VARCHAR(10),
    MADUAN VARCHAR(10),
    SOGIOLAMVIEC DECIMAL(10, 2) DEFAULT 0,
    PRIMARY KEY (MANHANVIEN, MADUAN)
);

ALTER TABLE T02_NHANVIEN 
ADD CONSTRAINT FK_NHANVIEN_PHONGBAN 
FOREIGN KEY (MAPHONGBAN) REFERENCES T01_PHONGBAN(MAPHONGBAN), 
ADD CONSTRAINT FK_NHANVIEN_NGUOIQUANLY 
FOREIGN KEY (MANGUOIQUANLY) REFERENCES T02_NHANVIEN(MANHANVIEN);

ALTER TABLE T01_PHONGBAN
ADD CONSTRAINT FK_PHONGBAN_TRUONGPHONG
FOREIGN KEY (MATRUONGPHONG) REFERENCES T02_NHANVIEN(MANHANVIEN);

ALTER TABLE T03_DUAN
ADD CONSTRAINT FK_DUAN_QUANLYDUAN
FOREIGN KEY (MAQUANLYDUAN) REFERENCES T02_NHANVIEN(MANHANVIEN);

ALTER TABLE T04_THAMGIADUAN
ADD CONSTRAINT FK_THAMGIADUAN_NHANVIEN
FOREIGN KEY (MANHANVIEN) REFERENCES T02_NHANVIEN(MANHANVIEN),
ADD CONSTRAINT FK_THAMGIADUAN_DUAN
FOREIGN KEY (MADUAN) REFERENCES T03_DUAN(MADUAN);

