    PRIMARY KEY (C05_EMPLOYEE_ID, C05_PROJECT_ID),
    CONSTRAINT FK_T05_T01 FOREIGN KEY(C05_EMPLOYEE_ID) REFERENCES T01_EMPLOYEE(C01_EMPLOYEE_ID),
	CONSTRAINT FK_T05_T04 FOREIGN KEY(C05_PROJECT_ID) REFERENCES T04_PROJECT(C04_PROJECT_ID)
