	C04_PROJECT_ID INT AUTO_INCREMENT,
    C04_PR0JECT_NAME VARCHAR(255),
    C04_MANAGER_ID INT, 
    C04_START_DATE DATE NOT NULL,
    C04_END_DATE DATE NOT NULL,
	C04_INCOME FLOAT NOT NULL,
    PRIMARY KEY (C04_PROJECT_ID),
    CONSTRAINT UNQ_C04_PR0JECT_NAME UNIQUE(C04_PR0JECT_NAME),
    CONSTRAINT FK_T04_T02 FOREIGN KEY(C04_MANAGER_ID) REFERENCES T02_MANAGER(C02_MANAGER_ID)
